-- Pop-Course 초기 데이터베이스 스키마
-- Supabase SQL Editor에서 파일 전체를 실행하면 테이블과 샘플 데이터가 생성됩니다.

-- 장소 정보를 저장하는 테이블입니다.
create table if not exists public.places (
    id bigint generated by default as identity primary key,
    name text not null,
    category text not null,
    lat double precision not null,
    lng double precision not null,
    address text not null,
    start_date date,
    end_date date,
    tags text[] not null default '{}',
    image_url text,
    created_at timestamptz not null default now()
);

-- 장소별 리뷰 링크를 저장하는 테이블입니다.
create table if not exists public.reviews (
    id bigint generated by default as identity primary key,
    place_id bigint not null references public.places(id) on delete cascade,
    title text not null,
    link text not null,
    snippet text,
    published_date date,
    created_at timestamptz not null default now()
);

-- 지도 필터링과 리뷰 조회가 잦으므로 검색용 인덱스를 추가합니다.
create index if not exists places_category_idx on public.places(category);
create index if not exists reviews_place_id_idx on public.reviews(place_id);

